#!/usr/bin/env node
// ui-foundry: compile design/tokens.json -> CSS variables (vanilla + Tailwind v4), a TS map,
// and the generated tables inside DESIGN.md.
//
//   node design/tools/tokens-build.mjs            build
//   node design/tools/tokens-build.mjs --check    exit 1 if anything is out of date (CI)
//   --root <dir>                                  project root (default: auto-detect)
import fs from 'node:fs';
import path from 'node:path';
import {
  parseArgs, findRoot, loadConfig, loadTokens, buildModel, spacingScale, TAILWIND_NAMESPACES,
  writeIfChanged, replaceBlock, setFrontmatterField, rel, c,
} from './lib/tokens.mjs';

const args = parseArgs();
const root = path.resolve(args.root || findRoot());
const cfg = loadConfig(root);

export function generate(root, cfg) {
  const { raw, json, hash } = loadTokens(root, cfg);
  const model = buildModel(json);
  if (model.errors.length) return { errors: model.errors, files: {} };
  const { vars } = model;
  const header = `/* AUTO-GENERATED by ui-foundry from ${cfg.designDir}/tokens.json (hash ${hash}). Do not edit — run \`npm run design:build\`. */\n`;
  const scale = spacingScale(json);
  const spaceVars = scale.map((n) => [`--space-${String(n).replace('.', '_')}`, n === 0 ? '0' : `calc(var(--spacing) * ${n})`]);
  const darkVars = vars.filter((v) => v.dark !== undefined);
  const line = (k, v) => `  ${k}: ${v};`;
  const allLines = (list) => list.flatMap((v) => [line(v.cssVar, v.light), ...v.extra.map((e) => line(e.cssVar, e.light))]);
  const darkSelector = ':root.dark, :root[data-theme="dark"]';
  const mediaSelector = ':root:not(.light):not([data-theme="light"])';
  const darkBlocks = (indent = '') => {
    const body = darkVars.map((v) => `${indent}  ${v.cssVar}: ${v.dark};`).join('\n');
    const out = [];
    if (cfg.darkMode.includes('class')) out.push(`${darkSelector} {\n  color-scheme: dark;\n${body}\n}`);
    if (cfg.darkMode.includes('media')) out.push(`@media (prefers-color-scheme: dark) {\n  ${mediaSelector} {\n    color-scheme: dark;\n${body.replace(/^ {2}/gm, '    ')}\n  }\n}`);
    return out.join('\n\n');
  };

  // ---- vanilla CSS -------------------------------------------------------
  const css = `${header}
:root {
  color-scheme: light;
${allLines(vars).join('\n')}
${spaceVars.map(([k, v]) => line(k, v)).join('\n')}
}

${darkBlocks()}
`;

  // ---- Tailwind v4 ------------------------------------------------------
  const inTheme = vars.filter((v) => v.tier === 'semantic' && TAILWIND_NAMESPACES.includes(v.group));
  const outTheme = vars.filter((v) => !inTheme.includes(v));
  const resets = (cfg.tailwind?.reset || []).map((ns) => `  --${ns}-*: initial;`);
  const customVariant = cfg.darkMode.includes('class')
    ? `@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));\n\n`
    : '';
  const tw = `${header}/* Import AFTER \`@import "tailwindcss";\` in your global stylesheet. */
${customVariant}@theme static {
${resets.join('\n')}
${allLines(inTheme).join('\n')}
}

:root {
  color-scheme: light;
${allLines(outTheme).join('\n')}
${spaceVars.map(([k, v]) => line(k, v)).join('\n')}
}

${darkBlocks()}
`;

  // ---- TypeScript map ----------------------------------------------------
  const tree = {};
  for (const v of vars) {
    const segs = v.path.split('.').slice(1);
    let node = tree;
    segs.slice(0, -1).forEach((s) => (node = node[s] ??= {}));
    node[segs[segs.length - 1]] = `var(${v.cssVar})`;
  }
  const list = vars.map((v) => ({ path: v.path, group: v.group, name: v.name, cssVar: v.cssVar, light: v.light, ...(v.dark ? { dark: v.dark } : {}) }));
  const ts = `// AUTO-GENERATED by ui-foundry from ${cfg.designDir}/tokens.json (hash ${hash}). Do not edit.
// Use these when a value must live in JS (charts, canvas, motion libs). Prefer classes/CSS vars otherwise.
export const tokens = ${JSON.stringify(tree, null, 2)} as const;

export const tokenList = ${JSON.stringify(list, null, 2)} as const;

export const tokensHash = '${hash}';
export type ColorToken = keyof typeof tokens.color;
`;

  // ---- DESIGN.md tables ----------------------------------------------------
  const twClass = (v) => {
    switch (v.group) {
      case 'color': return v.name.endsWith('foreground') ? `text-${v.name}` : `bg-${v.name}`;
      case 'font': return `font-${v.name}`;
      case 'weight': return `font-${v.name}`;
      case 'text': return `text-${v.name}`;
      case 'radius': return `rounded-${v.name}`;
      case 'shadow': return `shadow-${v.name}`;
      case 'ease': return `ease-${v.name}`;
      case 'duration': return `duration-(${v.cssVar})`;
      default: return `(${v.cssVar})`;
    }
  };
  const esc = (s) => String(s ?? '').replace(/\|/g, '\\|');
  const tableFor = (groups, cols) => {
    const rows = vars.filter((v) => v.tier === 'semantic' && groups.includes(v.group));
    if (!rows.length) return '_None defined._';
    const head = `| ${cols.map((c) => c[0]).join(' | ')} |\n| ${cols.map(() => '---').join(' | ')} |`;
    return head + '\n' + rows.map((v) => `| ${cols.map((c) => esc(c[1](v))).join(' | ')} |`).join('\n');
  };
  const code = (s) => (s ? `\`${s}\`` : '—');
  const blocks = {
    colors: tableFor(['color'], [
      ['Role', (v) => v.name], ['CSS var', (v) => code(v.cssVar)], ['Tailwind', (v) => code(twClass(v))],
      ['Light', (v) => code(v.light)], ['Dark', (v) => code(v.dark || v.light)], ['Intent', (v) => v.description || ''],
    ]),
    typography: [
      tableFor(['font', 'weight'], [['Token', (v) => v.path.replace('semantic.', '')], ['CSS var', (v) => code(v.cssVar)], ['Tailwind', (v) => code(twClass(v))], ['Value', (v) => code(v.light)]]),
      '',
      tableFor(['text'], [['Size', (v) => v.name], ['Tailwind', (v) => code(twClass(v))], ['Font size', (v) => code(v.light)], ['Line height', (v) => code(v.ext.lineHeight)], ['Tracking', (v) => code(v.ext.letterSpacing)], ['Use for', (v) => v.description || '']]),
    ].join('\n'),
    shape: [
      tableFor(['radius', 'shadow'], [['Token', (v) => v.path.replace('semantic.', '')], ['CSS var', (v) => code(v.cssVar)], ['Tailwind', (v) => code(twClass(v))], ['Light', (v) => code(v.light)], ['Dark', (v) => code(v.dark || '')]]),
      '',
      `Spacing base: \`--spacing: ${vars.find((v) => v.cssVar === '--spacing')?.light ?? '0.25rem'}\` — allowed steps: ${scale.map((n) => `\`${n}\``).join(', ')} (Tailwind \`p-4\`, \`gap-6\` … / CSS \`var(--space-4)\`).`,
    ].join('\n'),
    motion: tableFor(['ease', 'duration'], [['Token', (v) => v.path.replace('semantic.', '')], ['CSS var', (v) => code(v.cssVar)], ['Tailwind', (v) => code(twClass(v))], ['Value', (v) => code(v.light)], ['Use for', (v) => v.description || '']]),
  };

  const gen = path.join(root, cfg.generatedDir);
  const files = {};
  const styling = cfg.styling;
  files[path.join(gen, 'tokens.css')] = css;
  if (styling === 'tailwind' || styling === 'both') files[path.join(gen, 'tailwind.css')] = tw;
  files[path.join(gen, 'tokens.ts')] = ts;
  files[path.join(gen, 'manifest.json')] = JSON.stringify({ tokensHash: hash, generator: 'ui-foundry', varCount: vars.length }, null, 2) + '\n';

  const designMd = path.join(root, cfg.designDir, 'DESIGN.md');
  const missingBlocks = [];
  if (fs.existsSync(designMd)) {
    let text = fs.readFileSync(designMd, 'utf8');
    for (const [name, body] of Object.entries(blocks)) {
      const r = replaceBlock(text, name, body);
      if (!r.found) missingBlocks.push(name);
      text = r.text;
    }
    text = setFrontmatterField(text, 'tokens_hash', hash);
    files[designMd] = text;
  }
  return { errors: [], warnings: model.warnings, files, hash, missingBlocks, raw };
}

// ---- CLI ------------------------------------------------------------------
const isMain = import.meta.url === `file://${process.argv[1]}` || process.argv[1]?.endsWith('tokens-build.mjs');
if (isMain) {
  let result;
  try { result = generate(root, cfg); } catch (e) { console.error(c.red(`✖ ${e.message}`)); process.exit(1); }
  if (result.errors.length) {
    result.errors.forEach((e) => console.error(c.red(`✖ ${e}`)));
    process.exit(1);
  }
  (result.warnings || []).forEach((w) => console.warn(c.yellow(`⚠ ${w}`)));
  result.missingBlocks.forEach((b) => console.warn(c.yellow(`⚠ DESIGN.md has no generated block "${b}" — add <!-- ui-foundry:generated:${b} --> … <!-- /ui-foundry:generated:${b} -->`)));
  const stale = [];
  for (const [file, content] of Object.entries(result.files)) {
    if (args.check) {
      const prev = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
      if (prev !== content) stale.push(rel(root, file));
    } else if (writeIfChanged(file, content)) {
      console.log(c.green(`✔ wrote ${rel(root, file)}`));
    }
  }
  if (args.check) {
    if (stale.length) {
      console.error(c.red(`✖ Generated design files are stale (tokens hash ${result.hash}):`));
      stale.forEach((s) => console.error(`  - ${s}`));
      console.error('  Run: npm run design:build');
      process.exit(1);
    }
    console.log(c.green(`✔ generated files up to date (tokens ${result.hash})`));
  } else {
    console.log(c.dim(`tokens ${result.hash} · styling=${cfg.styling} · darkMode=${cfg.darkMode}`));
  }
}
